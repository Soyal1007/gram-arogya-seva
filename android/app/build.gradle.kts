// Release signing reads android/key.properties (git-ignored). Without it the
// release build falls back to the debug key so `flutter run --release` still
// works locally — but a debug-signed build cannot be uploaded to Play.
// key.properties format:
//   storePassword=...
//   keyPassword=...
//   keyAlias=upload
//   storeFile=C:/path/to/upload-keystore.jks
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

